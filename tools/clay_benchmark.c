/* Optional reference benchmark only; not linked into Paper or the layout library.
 * Download the pinned clay.h documented in LAYOUT.md into build/, then compile
 * clang -O3 -Ibuild tools/clay_benchmark.c -o build/clay-benchmark
 */
#define CLAY_IMPLEMENTATION
#include "clay.h"
#include <stdio.h>
#include <stdlib.h>
#include <time.h>

static double now(void) {
    struct timespec t;
    clock_gettime(CLOCK_MONOTONIC, &t);
    return t.tv_sec + t.tv_nsec * 1e-9;
}
static void error(Clay_ErrorData e) {
    fprintf(stderr, "%.*s\n", e.errorText.length, e.errorText.chars);
    exit(1);
}
static Clay_ElementDeclaration style(int i, int scenario) {
    return (Clay_ElementDeclaration){.layout = {
        .sizing = {scenario == 1 ? CLAY_SIZING_GROW(1, 5 + i % 17) : CLAY_SIZING_GROW(0), CLAY_SIZING_GROW(0)},
        .layoutDirection = CLAY_LEFT_TO_RIGHT, .childGap = 1}};
}
static void build(int count, int scenario) {
    Clay_BeginLayout();
    /* Same calls generated by CLAY_AUTO_ID, using a loop for deep hierarchies
       so C stack recursion does not become part of the comparison. */
    Clay__OpenElement();
    Clay__ConfigureOpenElement(style(0, 0));
    for (int i = 1; i < count; ++i) {
        Clay__OpenElement();
        Clay__ConfigureOpenElement(style(i, scenario));
        if (scenario != 2) Clay__CloseElement();
    }
    if (scenario == 2)
        for (int i = 1; i < count; ++i) Clay__CloseElement();
    Clay__CloseElement();
}
int main(void) {
    printf("scenario,nodes,sample,iterations,build_solve_us,arena_bytes,checksum\n");
    for (int scenario = 0; scenario < 3; ++scenario) {
        for (int count = 100; count <= 10000; count *= 10) {
            Clay_SetMaxElementCount(count + 16);
            uint32_t bytes = Clay_MinMemorySize();
            void *memory = malloc(bytes);
            Clay_Initialize(Clay_CreateArenaWithCapacityAndMemory(bytes, memory),
                            (Clay_Dimensions){count * 8, 800}, (Clay_ErrorHandler){error, NULL});
            int iterations = 100000 / count;
            double checksum = 0;
            for (int sample = 0; sample < 22; ++sample) {
                double start = now();
                for (int i = 0; i < iterations; ++i) {
                    Clay_SetLayoutDimensions((Clay_Dimensions){count * 8 + i % 2, 800});
                    build(count, scenario);
                    Clay_RenderCommandArray result = Clay_EndLayout(1.0f/60.0f);
                    Clay_LayoutElement *last = Clay_LayoutElementArray_Get(
                        &Clay_GetCurrentContext()->layoutElements,
                        Clay_GetCurrentContext()->layoutElements.length - 1);
                    Clay_ElementData element = Clay_GetElementData((Clay_ElementId){.id = last->id});
                    if (!element.found) { fprintf(stderr, "missing element\n"); exit(1); }
                    checksum += element.boundingBox.width + element.boundingBox.x + result.length;
                }
                double end = now();
                if (sample >= 2)
                    printf("%s,%d,%d,%d,%.6f,%u,%.0f\n",
                           scenario == 0 ? "wide" : scenario == 1 ? "bounded" : "deep",
                           count, sample - 2, iterations, (end - start) * 1e6 / iterations, bytes, checksum);
            }
            /* Clear the current context before releasing its arena. */
            Clay_SetCurrentContext(NULL);
            free(memory);
        }
    }
}
